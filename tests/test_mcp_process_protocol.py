"""MCP STDIO end-to-end checks using separate Python interpreter processes."""

from __future__ import annotations

import json
import os
from pathlib import Path
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]


def _request(identifier: int, method: str, params: dict | None = None) -> dict:
    message = {"jsonrpc": "2.0", "id": identifier, "method": method}
    if params is not None:
        message["params"] = params
    return message


def _call(identifier: int, name: str, arguments: dict) -> dict:
    return _request(identifier, "tools/call", {"name": name, "arguments": arguments})


def _run_mcp(tmp_path: Path, requests: list[dict | str]) -> dict[int | None, dict]:
    env = os.environ.copy()
    env["OS29_DB_PATH"] = str(tmp_path / "isolated-os29.db")
    env["OS29_LOG_DIR"] = str(tmp_path / "isolated-logs")
    input_text = "\n".join(
        request if isinstance(request, str) else json.dumps(request) for request in requests
    ) + "\n"
    response = subprocess.run(
        [sys.executable, "-m", "os29.mcp_stdio"],
        cwd=ROOT,
        env=env,
        capture_output=True,
        input=input_text,
        text=True,
        check=False,
        timeout=30,
    )
    assert response.returncode == 0, response.stderr
    lines = [json.loads(line) for line in response.stdout.splitlines() if line.strip()]
    assert len(lines) == len(requests), (response.stdout, response.stderr)
    assert all(line.get("jsonrpc") == "2.0" for line in lines)
    return {item["id"]: item for item in lines}


def _value(reply: dict) -> dict:
    assert "error" not in reply, reply
    assert reply["result"]["isError"] is False, reply
    return json.loads(reply["result"]["content"][0]["text"])


def test_real_mcp_stdio_handoff_across_independent_server_processes(tmp_path):
    work_id = "public-mcp-process-handoff-001"
    initial = _run_mcp(
        tmp_path,
        [
            _request(1, "initialize", {"protocolVersion": "2024-11-05"}),
            _request(2, "tools/list"),
            _call(3, "os29_work_unit_create", {
                "work_id": work_id,
                "project": "MCP cross-process demo",
                "objective": "Second MCP process resumes using a Work Unit ID",
                "owner_agent": "agent-a",
                "allowed_scope": ["temporary public test fixture"],
                "current_state": {"phase": "created"},
                "known_good": ["initial MCP worker process"],
                "known_bad": [],
                "open_issues": [],
                "next_steps": ["handoff to agent B"],
                "context_refs": [],
            }),
            _call(4, "os29_evidence_receipt_record", {
                "work_id": work_id,
                "actor_agent": "agent-a",
                "action": "persist first evidence",
                "outcome": "observed",
                "evidence": {"stage": "MCP process A"},
                "next_action": "resume by ID",
            }),
            _call(5, "os29_work_unit_handoff", {
                "work_id": work_id,
                "from_agent": "agent-a",
                "to_agent": "agent-b",
                "summary": "created in first MCP process",
                "next_action": "resume from a separate MCP process",
            }),
        ],
    )
    assert initial[1]["result"]["protocolVersion"] == "2024-11-05"
    tools = {tool["name"] for tool in initial[2]["result"]["tools"]}
    assert {"os29_work_unit_create", "os29_work_unit_handoff", "os29_work_unit_resume"} <= tools
    assert _value(initial[3])["work_id"] == work_id
    assert _value(initial[4])["trace_id"] == work_id
    assert _value(initial[5])["status"] == "handoff_ready"

    # A completely different MCP server subprocess recovers the durable
    # Work Unit using only the ID; no in-process Python objects are shared.
    recovered = _run_mcp(
        tmp_path,
        [_call(6, "os29_work_unit_resume", {"work_id": work_id, "agent_id": "agent-b"})],
    )
    result = _value(recovered[6])
    assert result["resumed_by"] == "agent-b"
    assert result["owner_agent"] == "agent-b"
    assert result["revision"] == 2
    assert result["evidence_receipt_count"] == 1
    assert "Second MCP process resumes" in result["context_pack"]

    # Evidence is generated by an actual executed Python subprocess and is
    # self-reported through MCP; it is not cryptographically attested.
    executed = subprocess.run(
        [sys.executable, "-c", "print('MCP_SMOKE_EXECUTED')"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
        timeout=10,
    )
    assert executed.returncode == 0
    assert executed.stdout.strip() == "MCP_SMOKE_EXECUTED"

    completed = _run_mcp(
        tmp_path,
        [
            _call(7, "os29_evidence_receipt_record", {
                "work_id": work_id,
                "actor_agent": "agent-b",
                "action": "execute real subprocess smoke",
                "outcome": "success",
                "evidence": {
                    "command": "python -c print(MCP_SMOKE_EXECUTED)",
                    "exit_code": executed.returncode,
                    "stdout": executed.stdout,
                    "stderr": executed.stderr,
                },
                "next_action": "complete",
            }),
            _call(8, "os29_work_unit_complete", {
                "work_id": work_id, "actor_agent": "agent-b", "expected_revision": 2,
            }),
            _call(9, "os29_work_unit_get", {"work_id": work_id}),
        ],
    )
    assert _value(completed[7])["outcome"] == "success"
    assert _value(completed[8])["status"] == "completed"
    assert _value(completed[9])["revision"] == 3

    final = _run_mcp(
        tmp_path,
        [_call(10, "os29_work_unit_resume", {"work_id": work_id, "agent_id": "agent-b"})],
    )
    assert _value(final[10])["status"] == "completed"
    assert _value(final[10])["evidence_receipt_count"] == 2


def test_mcp_invalid_json_recovers_and_reports_tool_errors(tmp_path):
    results = _run_mcp(
        tmp_path,
        [
            '{"jsonrpc":"2.0","id":1,"method":',
            _request(2, "ping"),
            _call(3, "unimplemented-fake-tool", {}),
        ],
    )
    assert results[None]["error"]["code"] == -32700
    assert results[2]["result"] == {}
    assert results[3]["result"]["isError"] is True
